#!/usr/bin/env python3
"""Detect a config policy twin that has drifted from its YAML source.

Several configs ship as a pair: a human-authored ``.yaml`` and a ``.json`` twin
that the Python readers load, because stdlib parses JSON without PyYAML. The
loaders prefer the JSON (`scripts/lib/resources.sh` hands
``config/resource-policy.json`` to ``resource_policy.py``), so a YAML edit that
forgets the twin is silently ignored: the Resource Guard keeps gating on the old
policy while the file an operator reads says something else.

This gate is the missing link. It parses both sides and compares them deeply,
and it reports the first path where they disagree rather than just "they differ".

Run directly: ``python3 tests/config_twin_check.py``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Final, NamedTuple, TypeAlias, cast

try:
    import yaml
except ModuleNotFoundError:  # pragma: no cover - exercised only on a thin interpreter
    sys.stderr.write(
        "config_twin_check: PyYAML is required to read the YAML side of the twins\n"
        "  (pip install pyyaml, or use the devcontainer / CI lint image)\n"
    )
    raise SystemExit(2)

#: One value a JSON document can hold, declared recursively so the walkers below
#: never have to widen to ``Any``.
JsonValue: TypeAlias = "bool | float | int | str | None | list[JsonValue] | dict[str, JsonValue]"


class Twin(NamedTuple):
    """One YAML/JSON pair that must describe the same document."""

    stem: str
    """Path under the repo root, without an extension."""

    load_bearing: bool
    """Whether a reader actually loads the JSON side, making drift a real hazard."""

    note: str
    """Why the pair exists, for the failure message."""


#: Every pair this repo keeps in step. `lab-domains.json` is generated by
#: ``scripts/lib/render_domains.py``; the other two are maintained by hand next
#: to their YAML, which is exactly where drift happens.
TWINS: Final[tuple[Twin, ...]] = (
    Twin(
        "config/resource-policy",
        load_bearing=True,
        note="resource_policy.py is handed the JSON, so a stale twin gates starts on old policy",
    ),
    Twin(
        "config/open-webui-policy",
        load_bearing=True,
        note="scripts/lib/open-webui.sh resolves the JSON path",
    ),
    Twin(
        "config/lab-domains",
        load_bearing=True,
        note="config/lab-domains.json is generated from the YAML by render_domains.py",
    ),
)


def load_json(path: Path) -> JsonValue:
    """Read one JSON document.

    Args:
        path: File to read.

    Returns:
        The decoded document.

    Raises:
        json.JSONDecodeError: If the file is not valid JSON.
    """
    decoded = json.loads(path.read_text())
    # A cast, not a validation pass: this module's job is to compare the two sides,
    # and a document that is not JSON at all is reported by the parse above.
    return cast(JsonValue, decoded)


def load_yaml(path: Path) -> JsonValue:
    """Read one YAML document.

    Args:
        path: File to read.

    Returns:
        The decoded document.

    Raises:
        yaml.YAMLError: If the file is not valid YAML.
    """
    loaded = yaml.safe_load(path.read_text())
    return cast(JsonValue, loaded)


def first_difference(left: JsonValue, right: JsonValue, at: str) -> str | None:
    """Find where two decoded documents first disagree.

    Args:
        left: The YAML-side document.
        right: The JSON-side document.
        at: Dotted path of ``left`` within the whole file, used for messages.

    Returns:
        A human-readable description of the first difference, or ``None`` when the
        two are equal.
    """
    if type(left) is not type(right) and not (_is_number(left) and _is_number(right)):
        return f"{at}: YAML has {type(left).__name__}, JSON has {type(right).__name__}"
    if isinstance(left, dict) and isinstance(right, dict):
        missing = sorted(set(left) - set(right))
        if missing:
            return f"{at}: missing from JSON: {', '.join(missing)}"
        extra = sorted(set(right) - set(left))
        if extra:
            return f"{at}: not in YAML: {', '.join(extra)}"
        # Deterministic order so the same drift always reports the same path.
        for key in sorted(left):
            nested = first_difference(left[key], right[key], f"{at}.{key}")
            if nested is not None:
                return nested
        return None
    if isinstance(left, list) and isinstance(right, list):
        if len(left) != len(right):
            return f"{at}: YAML lists {len(left)} items, JSON lists {len(right)}"
        for index, (left_item, right_item) in enumerate(zip(left, right)):
            nested = first_difference(left_item, right_item, f"{at}[{index}]")
            if nested is not None:
                return nested
        return None
    if left != right:
        return f"{at}: YAML {left!r}, JSON {right!r}"
    return None


def _is_number(value: JsonValue) -> bool:
    """True for the two numeric kinds JSON and YAML both produce.

    Args:
        value: Candidate value.

    Returns:
        ``True`` for ``int`` or ``float``, and not for ``bool``.
    """
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def check_twin(root: Path, twin: Twin) -> str | None:
    """Compare one twin pair.

    Args:
        root: Repository root.
        twin: The pair to check.

    Returns:
        A failure description, or ``None`` when the pair agrees.
    """
    yaml_path = root / f"{twin.stem}.yaml"
    json_path = root / f"{twin.stem}.json"
    for path in (yaml_path, json_path):
        if not path.is_file():
            return f"{twin.stem}: expected {path} to exist"
    try:
        left = load_yaml(yaml_path)
        right = load_json(json_path)
    except (json.JSONDecodeError, yaml.YAMLError) as error:
        return f"{twin.stem}: could not parse ({type(error).__name__}: {error})"
    return first_difference(left, right, twin.stem)


def main(argv: list[str]) -> int:
    """Check every twin pair and report.

    Args:
        argv: Argument vector; ``argv[1]`` may override the repo root.

    Returns:
        ``0`` when every pair agrees, ``1`` on the first drift found.
    """
    root = Path(argv[1]) if len(argv) > 1 else Path(__file__).resolve().parents[1]
    failures: list[str] = []
    for twin in TWINS:
        problem = check_twin(root, twin)
        if problem is not None:
            reason = f" ({twin.note})" if twin.load_bearing else ""
            failures.append(f"{problem}{reason}")
    if failures:
        for failure in failures:
            sys.stderr.write(f"config_twin_check: {failure}\n")
        sys.stderr.write(
            "config_twin_check: the JSON twin is what the readers load; regenerate it "
            "from the YAML (see the Source of truth header in each file)\n"
        )
        return 1
    sys.stdout.write(f"config_twin_check: {len(TWINS)} twin pair(s) agree\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
