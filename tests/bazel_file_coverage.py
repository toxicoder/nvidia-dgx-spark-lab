# Bazel control files it reads by itself; listing them would be noise.
_EXEMPT_NAMES = frozenset(
    {
        ".bazelignore",
        ".bazelrc",
        ".bazelversion",
        "BUILD",
        "BUILD.bazel",
        "MODULE.bazel",
        "MODULE.bazel.lock",
        "WORKSPACE",
        "WORKSPACE.bazel",
    }
)
# Git placeholders that carry no build meaning.
_EXEMPT_BASENAMES = frozenset({".gitkeep"})
# Operator runtime secrets: never a build input, never in a runfiles tree.
_EXEMPT_PREFIXES = ("secrets/",)
_EXEMPT_SUFFIXES = ("/.gitkeep",)
_DOTENV_PREFIX = ".env"


def _repo_root() -> pathlib.Path:
    """Resolve the repository root for Bazel and standalone invocations.

    Returns:
        Absolute path to the workspace root.
    """
    if env := os.environ.get("BUILD_WORKSPACE_DIRECTORY"):
        return pathlib.Path(env)
    return pathlib.Path(__file__).resolve().parent.parent


def _tracked(root: pathlib.Path) -> list[str]:
    """List git-tracked repository paths.

    Args:
        root: Repository root used as the git working directory.

    Returns:
        Sorted list of tracked relative POSIX paths.

    Raises:
        subprocess.CalledProcessError: If ``git ls-files`` fails.
    """
    out = subprocess.check_output(["git", "ls-files"], cwd=root, text=True)
    return sorted(line.strip() for line in out.splitlines() if line.strip())


def is_exempt(path: str) -> bool:
    """Return whether a tracked path is outside the Bazel ownership contract.

    Args:
        path: Repository-relative POSIX path.

    Returns:
        True when the path needs no ``BUILD.bazel`` owner.
    """
    if path.startswith(_EXEMPT_PREFIXES):
        return True
    name = path.rsplit("/", 1)[-1]
    if name in _EXEMPT_NAMES or name in _EXEMPT_BASENAMES:
        return True
    # ``.env`` and ``.env.<name>`` hold live secrets; ``.env.example`` is a
    # template that doubles as documentation and therefore needs an owner.
    if name == _DOTENV_PREFIX or (
        name.startswith(f"{_DOTENV_PREFIX}.") and not name.endswith(".example")
    ):
        return True
    return path.endswith(_EXEMPT_SUFFIXES)


def _is_path_like(value: str, bare_ok: bool = False) -> bool:
    """Return whether a string literal could name a repository file.

    Args:
        value: Literal extracted from a BUILD syntax tree.
        bare_ok: Accept a name with no separator or extension, such as
            ``Dockerfile`` or ``LICENSE``. True only in positions where Bazel
            requires a path, so tag and size strings cannot masquerade as files.

    Returns:
        True when the string is shaped like a relative file path.
    """
    if not value or value[0] in "@:/_%$":
        return False
    if any(char in value for char in _GLOB_CHARS):
        return False
    if any(char.isspace() for char in value) or "=" in value:
        return False
    if bare_ok:
        return True
    return "." in value or "/" in value


def _walk_pruning_globs(node: ast.AST) -> Iterator[ast.AST]:
    """Yield nodes below ``node`` without descending into ``glob()`` calls.

    Glob patterns and their ``exclude`` lists are matched separately, so they must
    not read as hand-written ownership.

    Args:
        node: Subtree root.

    Yields:
        Every node in the subtree except ``glob()`` call subtrees.
    """
    stack = [node]
    while stack:
        current = stack.pop()
        yield current
        if isinstance(current, ast.Call) and isinstance(current.func, ast.Name):
            if current.func.id == "glob":
                continue
        stack.extend(ast.iter_child_nodes(current))


def _literal_strings(node: ast.AST) -> set[str]:
    """Collect every string literal below a node, glob patterns included.

    Args:
        node: Subtree to walk.

    Returns:
        All string literals found below the node.
    """
    return {
        child.value
        for child in ast.walk(node)
        if isinstance(child, ast.Constant) and isinstance(child.value, str)
    }


def _strings_in_file_position(node: ast.AST, bare_ok: bool = False) -> set[str]:
    """Collect file-path literals from one expression subtree.

    Args:
        node: Subtree to walk (a list, tuple, binary concat, or call argument).
        bare_ok: Accept extension-less names; see _is_path_like.

    Returns:
        Path-like literals found below the node, excluding glob subtrees.
    """
    return {
        value
        for child in _walk_pruning_globs(node)
        for value in (
            [child.value]
            if isinstance(child, ast.Constant) and isinstance(child.value, str)
            else []
        )
        if _is_path_like(value, bare_ok)
    }


def _glob_specs(text: str) -> list[tuple[list[str], list[str], bool]]:
    """Extract every ``glob(patterns, exclude=..., allow_empty=...)`` call.

    Args:
        text: Contents of a ``BUILD.bazel`` file.

    Returns:
        One ``(patterns, excludes, allow_empty)`` triple per glob call.
    """
    tree = ast.parse(text, mode="exec")
    specs: list[tuple[list[str], list[str], bool]] = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)):
            continue
        if node.func.id != "glob" or not node.args:
            continue
        patterns = sorted(_literal_strings(node.args[0]))
        excludes: list[str] = []
        allow_empty = False
        for keyword in node.keywords:
            if keyword.arg == "exclude":
                excludes = sorted(_literal_strings(keyword.value))
            elif keyword.arg == "allow_empty":
                allow_empty = isinstance(keyword.value, ast.Constant) and bool(keyword.value.value)
        specs.append((patterns, excludes, allow_empty))
    return specs


def _glob_to_regex(pattern: str) -> re.Pattern[str]:
    """Translate a Bazel glob pattern into an anchored regex.

    Mirrors Bazel's rules: ``*`` and ``?`` stop at a path separator, ``**``
    crosses separators.

    Args:
        pattern: Bazel glob pattern, package-relative.

    Returns:
        Compiled pattern anchored to the whole path.
    """
    out: list[str] = []
    index = 0
    while index < len(pattern):
        if pattern.startswith("**/", index):
            out.append("(?:.*/)?")
            index += 3
        elif pattern.startswith("/**", index):
            out.append("/.*")
            index += 3
        elif pattern[index] == "*":
            out.append("[^/]*")
            index += 1
        elif pattern[index] == "?":
            out.append("[^/]")
            index += 1
        else:
            out.append(re.escape(pattern[index]))
            index += 1
    return re.compile("".join(out) + r"\Z")


def matches_glob(rel_path: str, patterns: list[str], excludes: list[str]) -> bool:
    """Return whether a package-relative path matches a glob spec.

    Args:
        rel_path: Path relative to the package that owns the glob.
        patterns: Glob patterns to match.
        excludes: Glob patterns to drop again.

    Returns:
        True when the path is included and not excluded.
    """
    included = any(_glob_to_regex(p).match(rel_path) for p in patterns)
    excluded = any(_glob_to_regex(p).match(rel_path) for p in excludes)
    return included and not excluded


def _collect_strings(text: str, package: str, attrs: frozenset[str]) -> set[str]:
    """Resolve the repository files a BUILD file names in the given attributes.

    Args:
        text: Contents of a ``BUILD.bazel`` file.
        package: Repository-relative package directory holding the file.
        attrs: Attribute names whose values are file lists.

    Returns:
        Repository-relative paths the file claims in those attributes.
    """
    tree = ast.parse(text, mode="exec")
    refs: set[str] = set()
    collecting_lists = attrs is not _OUTPUT_ATTRS

    for stmt in tree.body:
        if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant):
            continue  # Module or bare docstring: prose, not ownership.
        if isinstance(stmt, ast.Assign):
            if collecting_lists:
                refs.update(_strings_in_file_position(stmt.value))
            continue
        for node in _walk_pruning_globs(stmt):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            name = func.id if isinstance(func, ast.Name) else ""
            if name == "load":
                continue
            if name in _EXPORT_FUNCS and collecting_lists:
                for arg in node.args:
                    refs.update(_strings_in_file_position(arg, bare_ok=True))
                continue
            for keyword in node.keywords:
                if keyword.arg in attrs:
                    refs.update(_strings_in_file_position(keyword.value, bare_ok=True))

    prefix = "" if package in ("", ".") else f"{package}/"
    return {f"{prefix}{ref}" for ref in refs}


def parse_build_references(text: str, package: str) -> set[str]:
    """Resolve the repository files a BUILD file names explicitly.

    Module-level lists count as ownership declarations because BUILD files stage
    their ``srcs``/``data`` in them. Declared outputs are excluded; use
    parse_build_outputs for those.

    Args:
        text: Contents of a ``BUILD.bazel`` file.
        package: Repository-relative package directory holding the file.

    Returns:
        Repository-relative paths the file claims ownership of.
    """
    return _collect_strings(text, package, _FILE_ATTRS - _OUTPUT_ATTRS)


def parse_build_outputs(text: str, package: str) -> set[str]:
    """Resolve the outputs a BUILD file declares.

    Args:
        text: Contents of a ``BUILD.bazel`` file.
        package: Repository-relative package directory holding the file.

    Returns:
        Repository-relative paths declared as rule outputs.
    """
    return _collect_strings(text, package, _OUTPUT_ATTRS)


def bazelignore_prefixes(root: pathlib.Path) -> tuple[str, ...]:
    """Read the directories the workspace declares it never owns.

    ``.bazelignore`` is the written declaration of what stays out of the Bazel workspace.
    The walk has to honour it: ``next build`` copies an app's own ``BUILD.bazel`` into
    ``<app>/.next/standalone/``, and reading that generated tree as a package makes the gate
    report globs and dangling references that nobody wrote.

    Args:
        root: Repository root.

    Returns:
        Normalised directory prefixes, e.g. ``("dashboard/.next/", "node_modules/")``. A
        leading ``**/`` is preserved so it can match at any depth.
    """
    path = root / ".bazelignore"
    if not path.is_file():
        return ()
    prefixes: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue
        prefixes.append(entry.strip("/") + "/")
    return tuple(prefixes)


def _is_bazelignored(rel_path: str, prefixes: tuple[str, ...]) -> bool:
    """Report whether a repository-relative path sits under a Bazel-ignored directory.

    Args:
        rel_path: Repository-relative POSIX path.
        prefixes: Prefixes from :func:`bazelignore_prefixes`.

    Returns:
        True when the path lies inside an ignored directory at any depth.
    """
    for prefix in prefixes:
        if prefix.startswith("**/"):
            if f"/{prefix[3:]}" in f"/{rel_path}":
                return True
        elif rel_path.startswith(prefix):
            return True
    return False


def build_files(root: pathlib.Path) -> list[pathlib.Path]:
    """Find every BUILD file in the repository.

    Args:
        root: Repository root.

    Returns:
        Sorted BUILD files.
    """
    found = []
    ignored = bazelignore_prefixes(root)
    for path in sorted(root.rglob("BUILD*")):
        rel = path.relative_to(root).as_posix()
        if rel.startswith("bazel-") or path.name not in ("BUILD", "BUILD.bazel"):
            continue
        if _is_bazelignored(rel, ignored):
            continue
        found.append(path)
    return found


def _package_of(build_path: str) -> str:
    """Return the package directory a BUILD file belongs to.

    Args:
        build_path: Repository-relative BUILD file path.

    Returns:
        Repository-relative package directory, empty for the root package.
    """
    return build_path.rsplit("/", 1)[0] if "/" in build_path else ""


def collect_referenced_files(builds: dict[str, str]) -> set[str]:
    """Union the files claimed by name by every BUILD file in the repository.

    Args:
        builds: Mapping of repository-relative BUILD path to its contents.

    Returns:
        Repository-relative paths claimed by at least one BUILD file.
    """
    refs: set[str] = set()
    for build_path, text in builds.items():
        refs.update(parse_build_references(text, _package_of(build_path)))
    return refs


def collect_declared_outputs(builds: dict[str, str]) -> set[str]:
    """Union the outputs declared by every BUILD file in the repository.

    Args:
        builds: Mapping of repository-relative BUILD path to its contents.

    Returns:
        Repository-relative paths declared as rule outputs.
    """
    outs: set[str] = set()
    for build_path, text in builds.items():
        outs.update(parse_build_outputs(text, _package_of(build_path)))
    return outs


def collect_globbed_files(
    builds: dict[str, str], tracked: list[str], packages: set[str]
) -> set[str]:
    """Union the files claimed by ``glob()`` in every BUILD file.

    Mirrors Bazel by ignoring files that live in a nested package, since a
    package's glob never reaches into a child package.

    Args:
        builds: Mapping of repository-relative BUILD path to its contents.
        tracked: Repository-relative tracked paths.
        packages: Every directory that holds a BUILD file.

    Returns:
        Repository-relative paths matched by some glob.
    """
    claimed: set[str] = set()
    for build_path, text in builds.items():
        specs = _glob_specs(text)
        if not specs:
            continue
        package = _package_of(build_path)
        prefix = f"{package}/" if package else ""
        for path in tracked:
            if not path.startswith(prefix):
                continue
            rel = path[len(prefix) :]
            if any(f"{prefix}{parent}" in packages for parent in _parents(rel)):
                continue
            if any(matches_glob(rel, patterns, excludes) for patterns, excludes, _ in specs):
                claimed.add(path)
    return claimed


def _parents(rel_path: str) -> list[str]:
    """Return the ancestor directories of a package-relative path.

    Args:
        rel_path: Path relative to a package directory.

    Returns:
        Ancestor directories from deepest to shallowest.
    """
    parts = rel_path.split("/")[:-1]
    return ["/".join(parts[:i]) for i in range(len(parts), 0, -1)]


def collect_exact_glob_names(builds: dict[str, str]) -> set[str]:
    """Return paths named by ``glob()`` calls that contain no wildcard.

    ``glob(["package.json"])`` pins one path, so it is an explicit reference and
    needs no wildcard sanction.

    Args:
        builds: Mapping of repository-relative BUILD path to its contents.

    Returns:
        Repository-relative paths named without wildcards.
    """
    named: set[str] = set()
    for build_path, text in builds.items():
        package = _package_of(build_path)
        prefix = f"{package}/" if package else ""
        for patterns, _, allow_empty in _glob_specs(text):
            if allow_empty:
                # An optional, generated file (e.g. next-env.d.ts): it may be
                # absent on a fresh clone, so it claims nothing and must not be
                # treated as a missing hand-written reference.
                continue
            named.update(
                f"{prefix}{pattern}"
                for pattern in patterns
                if not any(char in pattern for char in _GLOB_CHARS)
            )
    return named


def glob_violations(builds: dict[str, str]) -> list[str]:
    """Report wildcards that are unsanctioned or whose sanction has gone stale.

    Only patterns that actually contain a wildcard are governed: a ``glob()`` of
    one literal path is an explicit listing.

    Args:
        builds: Mapping of repository-relative BUILD path to its contents.

    Returns:
        One ``"<build path>: <reason>"`` entry per policy violation.
    """
    problems: list[str] = []
    for build_path in sorted(builds):
        used = {
            pattern
            for patterns, _, _ in _glob_specs(builds[build_path])
            for pattern in patterns
            if any(char in pattern for char in _GLOB_CHARS)
        }
        allowed = set(SANCTIONED_GLOBS.get(build_path, {}))
        for pattern in sorted(used - allowed):
            problems.append(
                f"{build_path}: glob({pattern!r}) is not sanctioned — list the "
                "files explicitly, or add the pattern to SANCTIONED_GLOBS in "
                "tests/bazel_file_coverage.py with a reason"
            )
        for pattern in sorted(allowed - used):
            problems.append(
                f"{build_path}: SANCTIONED_GLOBS allows glob({pattern!r}) that the "
                "file no longer uses — drop the stale sanction"
            )
    return problems


def unowned_files(tracked: list[str], referenced: set[str]) -> list[str]:
    """Report tracked files that no Bazel rule claims.

    Args:
        tracked: Repository-relative tracked paths.
        referenced: Paths claimed by some BUILD file.

    Returns:
        Sorted unowned, non-exempt paths.
    """
    return sorted(path for path in tracked if not is_exempt(path) and path not in referenced)


def dangling_references(referenced: set[str], root: pathlib.Path) -> list[str]:
    """Report BUILD-named paths that do not exist on disk.

    Args:
        referenced: Paths claimed by name by some BUILD file.
        root: Repository root to resolve against.

    Returns:
        Sorted paths that were named but are missing.
    """
    return sorted(path for path in referenced if not (root / path).exists())


def main() -> int:
    """Run the Bazel file-coverage gate.

    Returns:
        Exit code 0 on success, 1 when violations are found.
    """
    root = _repo_root()
    builds: dict[str, str] = {}
    for path in build_files(root):
        builds[path.relative_to(root).as_posix()] = path.read_text(encoding="utf-8")

    tracked = _tracked(root)
    packages = {_package_of(build_path) for build_path in builds}
    referenced = collect_referenced_files(builds) | collect_exact_glob_names(builds)
    declared_outputs = collect_declared_outputs(builds)
    globbed = collect_globbed_files(builds, tracked, packages)

    violations: list[str] = []

    def report(label: str, items: list[str]) -> None:
        """Print one violation group to stderr and record it.

        Args:
            label: Human-readable name of the invariant that failed.
            items: Violation lines to show.
        """
        if not items:
            return
        print(f"bazel_file_coverage: {label} — {len(items)}", file=sys.stderr)
        for item in items[:60]:
            print(f"  - {item}", file=sys.stderr)
        if len(items) > 60:
            print(f"  ... and {len(items) - 60} more", file=sys.stderr)
        violations.extend(items)

    report(
        "unowned files (no Bazel rule claims them)",
        unowned_files(tracked, referenced | globbed | declared_outputs),
    )
    report("unsanctioned or stale glob() wildcards", glob_violations(builds))
    report(
        "dangling references (named by a BUILD file, missing on disk)",
        dangling_references(referenced - declared_outputs, root),
    )

    if violations:
        print("bazel_file_coverage: FAILED", file=sys.stderr)
        return 1

    owned = [path for path in tracked if not is_exempt(path)]
    by_name = len([path for path in owned if path in referenced])
    print(
        f"bazel_file_coverage: {len(owned)} tracked files owned "
        f"({by_name} named explicitly, "
        f"{len(owned) - by_name} covered by sanctioned globs or declared outputs)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
