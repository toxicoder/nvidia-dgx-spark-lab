#!/usr/bin/env python3
"""Bazel file-coverage gate: every tracked file is owned by a Bazel rule.

Enforces docs/project-conventions.md §15 (Bazel-first). Three invariants:

1. Ownership — every git-tracked file is claimed by some ``BUILD.bazel``, either
   by name (a ``srcs``/``data``/``tools`` entry, an ``exports_files`` entry, or a
   module-level list) or by a sanctioned ``glob()``. A file that no Bazel rule
   claims is invisible to the build graph and is reported.
2. Deliberate wildcards — explicit listings are the default. A ``glob()`` earns
   its place only where the file set is generated, tool-owned, or too volatile to
   enumerate; each pattern is pinned in SANCTIONED_GLOBS with a written reason.
   An unsanctioned wildcard, or a sanction whose pattern has gone unused, fails.
3. Soundness — a path a ``BUILD.bazel`` names by hand must exist on disk, so
   explicit lists cannot rot into fiction.

Exempt paths (see is_exempt) are the files Bazel reads implicitly or that are
operator runtime state; everything else needs a declared owner.
"""

from __future__ import annotations

import ast
import os
import pathlib
import re
import subprocess
import sys
from collections.abc import Iterator

# Attributes whose values are file lists. ``deps`` is absent: those are labels.
_FILE_ATTRS = frozenset({"srcs", "data", "outs", "tools"})
# Declared rule outputs: they are owned by Bazel and may not exist on disk yet.
_OUTPUT_ATTRS = frozenset({"outs"})
# Rules that take bare file paths as positional arguments.
_EXPORT_FUNCS = frozenset({"exports_files", "exports_dirs"})
# Glob metacharacters: a string containing one is a pattern, never a file.
_GLOB_CHARS = "*?["

# Wildcards that earn their keep, pinned per BUILD file with the reason. Adding a
# wildcard means adding a line here and justifying it; everything else is listed
# by name so a new file stays a deliberate, reviewable edit. A wildcard is
# justified when the tree is generated or tool-owned, or when a framework copies
# it wholesale and per-file naming would add churn without adding safety.
