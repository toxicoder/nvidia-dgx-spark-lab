# ## nvidia-dgx-spark-lab management script
#
# Simple, safe wrapper for operating heavy inference workloads on 1-5 DGX Spark nodes.
#
# SCALABLE for 1-5 DGX Spark nodes (high-speed linked for 2+).
#
# - Works with 1 node (single control-plane + worker, local multi-GPU NCCL).
# - Scales to 2-5 nodes with inter-node NCCL over the fabric's high-speed links.
# - Tailored for small clusters; for larger see notes in docs.
#
# Core safety philosophy (enforced by this script and the workloads):
#
# - Nothing starts automatically on reboot.
# - Heavy jobs use restartPolicy: OnFailure + very low backoffLimit.
# - Explicit resources.requests + limits on every container.
# - Full workloads require interactive confirmation + capacity checks.
# - Always run `stop` (or `stop-dev`) before rebooting nodes.
#
# This script (and its libs) are the primary source for the
# auto-generated Shell reference. Structured comments here power
# the nice human-readable docs under Reference → Shell Commands & Helpers.
#
# See:
#   docs/generated/shell/reference.md
#   bazelisk run //docs:docs
