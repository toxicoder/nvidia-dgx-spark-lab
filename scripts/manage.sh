# @function stop_workloads
# @command stop
# Stop all inference jobs and Ray workloads plus dev components.
# Safe to run before node reboot.
#
# Usage:
#   bazelisk run //:manage -- stop
#   ./scripts/manage.sh stop
#
# Safety:
#   Always run stop (and stop-visual / stop-stack-rounded as needed) before reboot.
#   Does not auto-start anything afterward.

stop_workloads() {
  log "Stopping managed workloads (all models + ray)..."
  # Specific for test compatibility + labels for generality
  kubectl delete job kimi kimi-test nemotron-3-ultra glm-5.2 glm-5.2-rpc ray-head ray-worker -n "${NAMESPACE}" --ignore-not-found=true --grace-period=30 || true
  kubectl delete job -l workload=inference -n "${NAMESPACE}" --ignore-not-found=true --grace-period=30 || true
  kubectl delete job -l workload=ray -n "${NAMESPACE}" --ignore-not-found=true --grace-period=30 || true
  kubectl delete pod -l workload=inference -n "${NAMESPACE}" --ignore-not-found=true --grace-period=30 || true
  kubectl delete pod -l workload=ray -n "${NAMESPACE}" --ignore-not-found=true --grace-period=30 || true
  stop_dev_workloads || true
  log "Workloads stopped. Pods may still be terminating."
}

# @function cleanup
# @command cleanup
# Destructive namespace cleanup after interactive DELETE confirmation.
# Deletes ai-inference and dev namespace resources.

cleanup() {
  warn "This will delete ALL resources in namespace ${NAMESPACE} managed by this lab."
  read -r -p "Type 'DELETE' to confirm full cleanup: " confirm
  if [[ $confirm != "DELETE" ]]; then
    log "Cleanup aborted."
    exit 0
  fi

  stop_workloads
  kubectl delete svc kimi kimi-test nemotron-3-ultra glm-5.2 ray-head ray-worker -n "${NAMESPACE}" --ignore-not-found || true
  kubectl delete svc -l workload=inference -n "${NAMESPACE}" --ignore-not-found || true
  kubectl delete svc -l workload=ray -n "${NAMESPACE}" --ignore-not-found || true
  kubectl delete ns "${NAMESPACE}" --ignore-not-found || true
  # Dev ns (non-destructive on purpose; user can delete explicitly)
  for ns in coder kasm monitoring dev; do
    kubectl delete all,cm,secret,sa,role,rolebinding -n "$ns" --all --ignore-not-found || true
  done
  log "Cleanup complete."
}

# @command start-test
# Start the safe lightweight test workload (recommended first step).
# Uses lower resources (2 GPUs) for validation. Includes pre-flights.
#
# Usage:
#   bazelisk run //:manage -- start-test
#   ./scripts/manage.sh start-test
#
# Safety:
#   Lighter model (2 GPU / 32Gi request, backoffLimit 2). Still runs access +
#   namespace checks. Required first Job on a new or patched cluster.
#   Dashboard: http://{{SPARK0_IP}}:{{DASHBOARD_PORT}}
#   See start-kimi for full production (after validation).
#
# @command start-kimi
# @command start-full
# Deploy the FULL heavy kimi workload (with confirmation + checks).
# Requests 8 GPUs + 128Gi+ memory. Only after start-test + start-ray on sufficient capacity.
#
# Usage:
#   ./scripts/manage.sh start-kimi
#   {{SPARK0_IP:=<your-spark0>}} ./scripts/manage.sh start-kimi
#
# Safety:
#   Requires interactive confirmation ("yes"). Pre-checks for existing kimi job and approx free GPUs.
#   Heavy: can impact host if resources exceeded. Always stop before reboot.
#
# @command start-ray
# Deploy Ray head+worker for multi-node (two-node) distributed workloads.
# Prerequisite for large models like nemotron/glm.
#
# Usage:
#   ./scripts/manage.sh start-ray
#
# Safety:
#   Starts orchestration; uses modest resources for head. Workers only on multi-node.
#   Run doctor/estimate first.
#
# @command start-nemotron
# @command start-nemotron-3-ultra
# Heavy NVFP4 Nemotron model (validate first; 2+ nodes preferred).
#
# Usage:
#   ./scripts/manage.sh start-nemotron
#
# Safety:
#   Requires confirmation + starts Ray first. Significant resources.
#   {{PLACEHOLDER}} edit as needed.
#
# @command start-glm
# @command start-glm-5.2
# Heavy GLM-5.2 1-bit UD-IQ1_M via llama.cpp RPC (validate first; 2 nodes required).
#
# Usage:
#   ./scripts/manage.sh start-glm
#
# Safety:
#   Requires confirmation. Starts spark1 RPC backend then spark0 server (no Ray).
#   Quality trade-off vs higher quants. See models-catalog.md .

case "${1:-help}" in
  status)
    ## status
    # @command status
    # Show cluster nodes, GPU resources (allocatable vs capacity), workloads,
    # recent events, dev workspaces, and convenient browser URLs.
    #
    # Usage:
    #   ./scripts/manage.sh status
    #   bazelisk run //:manage -- status
    #
    # Safety:
    #   Completely read-only. The single safest command to run at any time.
    require_kubectl
    check_cluster_access
    print_status
    print_dev_status || true
    print_access_info || true
    ;;
  start-test)
    ## start-test
    # Start the safe lightweight test workload (recommended first step).
    # Uses lower resources for validation. Includes pre-flights.
    require_kubectl
    check_cluster_access
    start_test
    ;;
  start-kimi | start-full)
    ## start-kimi
    # Start full heavy Kimi production workload (confirmation + high resources required).
    # Only after test + ray validation on sufficient capacity.
    require_kubectl
    check_cluster_access
    start_kimi
